/// Home-relative directory that contains the projects Mac Cleaner inspects.
pub const PROJECTS_ROOT: &str = "Documents/GitHub";

const fn named(
    id: &'static str,
    display_name: &'static str,
    home_relative_root: &'static str,
    entry: &'static str,
    owner: &'static str,
    reason: &'static str,
) -> TargetSpec {
    TargetSpec {
        id,
        display_name,
        home_relative_root,
        category: "Dependency download cache",
        reason,
        owner,
        recovery: "The tool downloads what it needs again on next use",
        recovery_mode: RecoveryMode::Redownload,
        safety_tier: SafetyTier::ReviewRequired,
        minimum_age: Duration::ZERO,
        layout: TargetLayout::Named(entry),
        require_git_ignored: false,
    }
}

/// A named cache directory that is offered only after it has sat idle.
const fn aged_named(
    id: &'static str,
    display_name: &'static str,
    home_relative_root: &'static str,
    entry: &'static str,
    owner: &'static str,
    reason: &'static str,
    idle_hours: u64,
) -> TargetSpec {
    TargetSpec {
        minimum_age: Duration::from_hours(idle_hours),
        ..named(id, display_name, home_relative_root, entry, owner, reason)
    }
}

